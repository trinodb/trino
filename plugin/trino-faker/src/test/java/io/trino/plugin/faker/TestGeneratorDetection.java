package io.trino.plugin.faker;

import io.trino.plugin.faker.GeneratorDetection.NamedGenerator;
import net.datafaker.Faker;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Locale;
import java.util.Random;
import java.util.stream.IntStream;
import java.util.stream.Stream;

import static com.google.common.collect.ImmutableList.toImmutableList;
import static io.trino.plugin.faker.GeneratorDetection.GENERATORS;
import static io.trino.plugin.faker.GeneratorDetection.detectGenerator;
import static io.trino.spi.type.CharType.createCharType;
import static io.trino.spi.type.IntegerType.INTEGER;
import static io.trino.spi.type.VarbinaryType.VARBINARY;
import static io.trino.spi.type.VarcharType.VARCHAR;
import static io.trino.spi.type.VarcharType.createVarcharType;
import static org.assertj.core.api.Assertions.assertThat;

final class TestGeneratorDetection
{
    // The default locale, and locales generating the longest values for some of the expressions
    private static final List<Locale> LOCALES = Stream.of("en", "ar", "de", "el-GR", "en-IN", "es-PY", "fa", "ka", "pt-BR", "sk")
            .map(Locale::forLanguageTag)
            .collect(toImmutableList());

    @Test
    void testGeneratedValuesFitMinColumnLength()
    {
        for (NamedGenerator generator : GENERATORS) {
            for (Locale locale : LOCALES) {
                Faker faker = new Faker(locale, new Random(1));
                int maxLength = IntStream.range(0, 10_000)
                        .mapToObj(_ -> faker.expression(generator.expression()))
                        .mapToInt(value -> value.codePointCount(0, value.length()))
                        .max()
                        .orElseThrow();
                assertThat(maxLength)
                        .describedAs("longest value generated by %s in locale %s", generator.expression(), locale)
                        .isLessThanOrEqualTo(generator.minColumnLength());
            }
        }
    }

    @Test
    void testDetectGenerator()
    {
        assertThat(detectGenerator("email", VARCHAR)).hasValue("#{Internet.emailAddress}");
        assertThat(detectGenerator("first_name", VARCHAR)).hasValue("#{Name.first_name}");
        assertThat(detectGenerator("FirstName", VARCHAR)).hasValue("#{Name.first_name}");
        assertThat(detectGenerator("first-name", VARCHAR)).hasValue("#{Name.first_name}");
        assertThat(detectGenerator("First Name", VARCHAR)).hasValue("#{Name.first_name}");
        assertThat(detectGenerator("postal_code", VARCHAR)).hasValue("#{Address.zipCode}");
        assertThat(detectGenerator("name", VARCHAR)).isEmpty();
        assertThat(detectGenerator("customer_email", VARCHAR)).isEmpty();
    }

    @Test
    void testDetectGeneratorForBoundedColumns()
    {
        assertThat(detectGenerator("email", createVarcharType(60))).hasValue("#{Internet.emailAddress}");
        assertThat(detectGenerator("email", createVarcharType(59))).isEmpty();
        assertThat(detectGenerator("country_code", createCharType(2))).hasValue("#{Country.countryCode2}");
        assertThat(detectGenerator("country_code", createCharType(1))).isEmpty();
        assertThat(detectGenerator("country_code", createVarcharType(1))).isEmpty();
    }

    @Test
    void testDetectGeneratorForOtherTypes()
    {
        assertThat(detectGenerator("email", VARBINARY)).isEmpty();
        assertThat(detectGenerator("zip", INTEGER)).isEmpty();
    }
}
